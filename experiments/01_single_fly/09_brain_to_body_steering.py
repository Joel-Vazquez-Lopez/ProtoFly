"""Experiment 01D: whole-brain neural activity drives body steering.

Extends the validated DNa02 steering-readout experiment by connecting
actual DNa02 activity generated by the current whole-brain model to a
simulated FlyBody through the explicit SteeringActuator interface.

The steering gain used here is an engineering test parameter. It is not
a biologically calibrated mapping between DNa02 firing rate and angular
velocity.

This experiment validates the brain-to-body interface only. Sugar is
used as the established reproducible sensory perturbation and is not
interpreted as a spatial steering target.
"""

import math
import pandas as pd

from brian2 import (
    PoissonGroup,
    Synapses,
    SpikeMonitor,
    Network,
    Hz,
    ms,
    seed,
)

from protofly.environment.feeding import FeedingEnvironment
from protofly.connectome.known_neurons import steering_descending_root_ids
from protofly.connectome.network import build_flywire_network
from protofly.neural.lif import DEFAULT_PARAMS
from protofly.agents.body import FlyBody
from protofly.agents.steering_readout import SteeringReadout
from protofly.agents.steering_actuator import SteeringActuator


SUGAR_GRNS = [
    720575940624963786,
    720575940630233916,
    720575940637568838,
    720575940638202345,
    720575940617000768,
    720575940630797113,
    720575940632889389,
    720575940621754367,
    720575940621502051,
    720575940640649691,
    720575940639332736,
    720575940616885538,
    720575940639198653,
    720575940620900446,
    720575940617937543,
    720575940632425919,
    720575940633143833,
    720575940612670570,
    720575940628853239,
    720575940629176663,
    720575940611875570,
]

SUGAR_RATE = 100 * Hz
DURATION = 1000 * ms
SEED = 42

# Explicit simulation-level test parameter.
# Units: rad / (s * Hz)
STEERING_GAIN = 0.01


# ------------------------------------------------------------
# Build current FlyWire brain.
# ------------------------------------------------------------

print("Loading current FlyWire brain...")

neurons_df = pd.read_csv(
    "data/raw/flywire/neurons.csv.gz"
)

connections_df = pd.read_csv(
    "data/raw/flywire/connections_princeton.csv.gz"
)

neuron_ids = neurons_df["root_id"].tolist()

neurons, synapses, index, circuit = build_flywire_network(
    neuron_ids,
    neurons_df,
    connections_df,
)


# ------------------------------------------------------------
# Identify biological sensory and steering neurons.
# ------------------------------------------------------------

sugar_indices = [
    index[fly_id]
    for fly_id in SUGAR_GRNS
    if fly_id in index
]

steering_ids = steering_descending_root_ids()

missing_steering = {
    name: root_id
    for name, root_id in steering_ids.items()
    if root_id not in index
}

if missing_steering:
    raise RuntimeError(
        "Verified steering descending neurons missing from substrate: "
        f"{missing_steering}"
    )

steering_indices = {
    name: index[root_id]
    for name, root_id in steering_ids.items()
}

print(f"Brain neurons:        {len(neurons_df):,}")
print(f"Sugar GRNs present:   {len(sugar_indices)}/{len(SUGAR_GRNS)}")
print(f"Steering DNs present: {len(steering_indices)}/{len(steering_ids)}")


# ------------------------------------------------------------
# Sensory interface.
# ------------------------------------------------------------

stimulus = PoissonGroup(
    len(sugar_indices),
    rates=0 * Hz,
)

sensory_synapses = Synapses(
    stimulus,
    neurons,
    model="w : volt",
    on_pre="v_post += w",
)

sensory_synapses.connect(
    i=list(range(len(sugar_indices))),
    j=sugar_indices,
)

sensory_synapses.w = DEFAULT_PARAMS["w_syn"] * 250

for i in sugar_indices:
    neurons.rfc[i] = 0 * ms


# ------------------------------------------------------------
# Neural observation.
# ------------------------------------------------------------

spikes = SpikeMonitor(neurons)

network = Network(
    neurons,
    synapses,
    stimulus,
    sensory_synapses,
    spikes,
)

network.store("initial")


# ------------------------------------------------------------
# Body and neural-to-body interface.
# ------------------------------------------------------------

body = FlyBody(
    x=5.0,
    y=4.0,
    orientation=0.0,
)

steering_actuator = SteeringActuator(
    steering_gain=STEERING_GAIN
)


# ------------------------------------------------------------
# Environment -> brain -> DNa02 -> body.
# ------------------------------------------------------------

network.restore("initial")
seed(SEED)

environment = FeedingEnvironment(
    sugar_present=True,
    sugar_amount=1.0,
)

if environment.sugar_contact():
    stimulus.rates = SUGAR_RATE
else:
    stimulus.rates = 0 * Hz

initial_orientation = body.orientation

network.run(DURATION)

counts = spikes.count[:]

left_spikes = int(
    counts[steering_indices["DNa02_L"]]
)

right_spikes = int(
    counts[steering_indices["DNa02_R"]]
)

readout = SteeringReadout()

duration_seconds = float(
    DURATION / (1000 * ms)
)

readout.update(
    left_spikes=left_spikes,
    right_spikes=right_spikes,
    duration_seconds=duration_seconds,
)

angular_displacement = steering_actuator.execute(
    readout=readout,
    body=body,
    duration_seconds=duration_seconds,
)


# ------------------------------------------------------------
# Report.
# ------------------------------------------------------------

print()
print("=== WHOLE-BRAIN -> BODY STEERING ===")

print()
print("Neural output:")
print(f"  DNa02_L:        {left_spikes} spikes")
print(f"  DNa02_R:        {right_spikes} spikes")
print(f"  Left rate:      {readout.left_rate:.2f} Hz")
print(f"  Right rate:     {readout.right_rate:.2f} Hz")
print(f"  Steering drive: {readout.steering_drive:+.2f} Hz")

print()
print("Embodiment mapping:")
print(f"  Test gain:      {STEERING_GAIN:.4f} rad/(s*Hz)")
print(
    f"  Displacement:   "
    f"{angular_displacement:+.4f} rad "
    f"({math.degrees(angular_displacement):+.2f} deg)"
)

print()
print("Body state:")
print(
    f"  Initial orientation: "
    f"{initial_orientation:.4f} rad "
    f"({math.degrees(initial_orientation):.2f} deg)"
)
print(
    f"  Final orientation:   "
    f"{body.orientation:.4f} rad "
    f"({math.degrees(body.orientation):.2f} deg)"
)

print()
print(f"  Position: ({body.x:.2f}, {body.y:.2f})")


# ------------------------------------------------------------
# Integration checks.
# ------------------------------------------------------------

expected_displacement = (
    STEERING_GAIN
    * readout.steering_drive
    * duration_seconds
)

if not math.isclose(
    angular_displacement,
    expected_displacement,
    rel_tol=1e-12,
    abs_tol=1e-12,
):
    raise RuntimeError(
        "Steering actuator displacement does not match neural readout."
    )

if readout.steering_drive > 0 and angular_displacement <= 0:
    raise RuntimeError(
        "Positive neural steering drive produced incorrect rotation sign."
    )

if readout.steering_drive < 0 and angular_displacement >= 0:
    raise RuntimeError(
        "Negative neural steering drive produced incorrect rotation sign."
    )

if body.x != 5.0 or body.y != 4.0:
    raise RuntimeError(
        "Steering experiment unexpectedly changed body position."
    )

print()
print("PASS: actual whole-brain DNa02 activity changed FlyBody orientation.")