"""Experiment 16: embodied walking/feeding competition.

Tests whether the walking/feeding neural competition established in
Experiment 14 produces a corresponding difference in embodied forward
locomotion.

Two independent conditions are compared:

    1. Bilateral BPN stimulation at 50 Hz.
    2. Bilateral BPN stimulation at 50 Hz plus sugar GRNs at 150 Hz.

For each condition:

    stimulation
        -> full FlyWire FAFB v783 connectome
        -> bilateral DNg100 activity
        -> identical forward-locomotion readout
        -> identical simulation-level forward actuator
        -> FlyBody displacement

The behavioral difference is therefore not imposed by a separate
"sugar means stop" rule. Both conditions use the same DNg100-to-body
mapping; any difference in forward displacement follows from the
DNg100 activity generated by the connectome-constrained simulation.

The DNg100-to-displacement mapping remains an explicit simulation-level
embodiment assumption and is not a biologically calibrated walking-speed
model.
"""

import numpy as np
import pandas as pd

from brian2 import (
    PoissonGroup,
    Synapses,
    SpikeMonitor,
    StateMonitor,
    Network,
    Hz,
    ms,
    mV,
    seed,
)

from protofly.connectome.known_neurons import (
    BOLT_PROTOCEREBRAL_NEURONS,
    FORWARD_LOCOMOTION_DESCENDING_NEURONS,
)
from protofly.connectome.network import build_flywire_network
from protofly.neural.lif import DEFAULT_PARAMS

from protofly.agents.body import FlyBody
from protofly.agents.locomotion_readout import LocomotionReadout
from protofly.agents.locomotion_actuator import (
    LocomotionActuator,
    LocomotionCommand,
    LocomotionCommandType,
)
from protofly.environment.spatial import SpatialEnvironment


SUGAR_GRNS = [
    720575940624963786,
    720575940630233916,
    720575940637568838,
    720575940638202345,
    720575940617000768,
    720575940630797113,
    720575940632889389,
    720575940621754367,
    720575940621502051,
    720575940640649691,
    720575940639332736,
    720575940616885538,
    720575940639198653,
    720575940620900446,
    720575940617937543,
    720575940632425919,
    720575940633143833,
    720575940612670570,
    720575940628853239,
    720575940629176663,
    720575940611875570,
]

BPN_RATE = 50 * Hz
SUGAR_RATE = 150 * Hz
DURATION = 1000 * ms
BIN_SIZE = 50 * ms
# Explicit simulation-level embodiment parameter.
# This is NOT a biologically calibrated DNg100 -> walking-speed mapping.
# Units: body-distance units / (s * Hz)
FORWARD_GAIN = 0.01
SEED = 42


BPN_ROOT_IDS = [
    root_id
    for data in BOLT_PROTOCEREBRAL_NEURONS.values()
    for side in ("left", "right")
    for root_id in data[side]
]


# ------------------------------------------------------------
# Load connectome data once.
# ------------------------------------------------------------

print("Loading current FlyWire brain...")

neurons_df = pd.read_csv(
    "data/raw/flywire/neurons.csv.gz"
)

connections_df = pd.read_csv(
    "data/raw/flywire/connections_princeton.csv.gz"
)

neuron_ids = neurons_df["root_id"].tolist()


# ------------------------------------------------------------
# Run one experimental condition in a fresh brain.
# ------------------------------------------------------------

def run_condition(include_sugar, trial_seed):
    neurons, synapses, index, circuit = build_flywire_network(
        neuron_ids,
        neurons_df,
        connections_df,
    )

    bpn_indices = [
        index[root_id]
        for root_id in BPN_ROOT_IDS
        if root_id in index
    ]

    sugar_indices = [
        index[root_id]
        for root_id in SUGAR_GRNS
        if root_id in index
    ]

    dng100_left_root = (
        FORWARD_LOCOMOTION_DESCENDING_NEURONS["DNg100"]["left"]
    )
    dng100_right_root = (
        FORWARD_LOCOMOTION_DESCENDING_NEURONS["DNg100"]["right"]
    )

    dng100_left_index = index[dng100_left_root]
    dng100_right_index = index[dng100_right_root]

    # --------------------------------------------------------
    # BPN stimulation.
    # --------------------------------------------------------

    bpn_stimulus = PoissonGroup(
        len(bpn_indices),
        rates=BPN_RATE,
    )

    bpn_stimulus_synapses = Synapses(
        bpn_stimulus,
        neurons,
        model="w : volt",
        on_pre="v_post += w",
    )

    bpn_stimulus_synapses.connect(
        i=list(range(len(bpn_indices))),
        j=bpn_indices,
    )

    bpn_stimulus_synapses.w = DEFAULT_PARAMS["w_syn"] * 250

    for i in bpn_indices:
        neurons.rfc[i] = 0 * ms

    network_objects = [
        neurons,
        synapses,
        bpn_stimulus,
        bpn_stimulus_synapses,
    ]

    # --------------------------------------------------------
    # Optional sugar-GRN stimulation.
    # --------------------------------------------------------

    if include_sugar:
        sugar_stimulus = PoissonGroup(
            len(sugar_indices),
            rates=SUGAR_RATE,
        )

        sugar_stimulus_synapses = Synapses(
            sugar_stimulus,
            neurons,
            model="w : volt",
            on_pre="v_post += w",
        )

        sugar_stimulus_synapses.connect(
            i=list(range(len(sugar_indices))),
            j=sugar_indices,
        )

        sugar_stimulus_synapses.w = DEFAULT_PARAMS["w_syn"] * 250

        for i in sugar_indices:
            neurons.rfc[i] = 0 * ms

        network_objects.extend([
            sugar_stimulus,
            sugar_stimulus_synapses,
        ])

    # --------------------------------------------------------
    # Record DNg100 activity.
    # --------------------------------------------------------

    spikes = SpikeMonitor(neurons)

    dng100_voltage = StateMonitor(
        neurons,
        "v",
        record=[
            dng100_left_index,
            dng100_right_index,
        ],
    )

    network_objects.extend([
        spikes,
        dng100_voltage,
    ])

    network = Network(*network_objects)

    seed(trial_seed)
    network.run(DURATION)

    # --------------------------------------------------------
    # Extract DNg100 activity.
    # --------------------------------------------------------

    spike_indices = np.asarray(spikes.i[:])
    spike_times_ms = np.asarray(spikes.t[:] / ms)

    left_times = spike_times_ms[
        spike_indices == dng100_left_index
    ]

    right_times = spike_times_ms[
        spike_indices == dng100_right_index
    ]

    duration_ms = float(DURATION / ms)
    bin_size_ms = float(BIN_SIZE / ms)

    bin_edges = np.arange(
        0.0,
        duration_ms + bin_size_ms,
        bin_size_ms,
    )

    left_counts, _ = np.histogram(
        left_times,
        bins=bin_edges,
    )

    right_counts, _ = np.histogram(
        right_times,
        bins=bin_edges,
    )

    left_voltage_mv = np.asarray(
        dng100_voltage.v[0] / mV
    )

    right_voltage_mv = np.asarray(
        dng100_voltage.v[1] / mV
    )

    voltage_times_ms = np.asarray(
        dng100_voltage.t[:] / ms
    )

    left_voltage_means = []
    right_voltage_means = []

    for i in range(len(bin_edges) - 1):
        start = bin_edges[i]
        end = bin_edges[i + 1]

        mask = (
            (voltage_times_ms >= start)
            & (voltage_times_ms < end)
        )

        left_voltage_means.append(
            left_voltage_mv[mask].mean()
        )

        right_voltage_means.append(
            right_voltage_mv[mask].mean()
        )

    left_voltage_means = np.asarray(left_voltage_means)
    right_voltage_means = np.asarray(right_voltage_means)

    total_left = int(left_counts.sum())
    total_right = int(right_counts.sum())

    direct_left = int(
        spikes.count[dng100_left_index]
    )
    direct_right = int(
        spikes.count[dng100_right_index]
    )

    if total_left != direct_left:
        raise RuntimeError(
            f"Left binned total {total_left} != "
            f"SpikeMonitor total {direct_left}"
        )

    if total_right != direct_right:
        raise RuntimeError(
            f"Right binned total {total_right} != "
            f"SpikeMonitor total {direct_right}"
        )

    return {
        "bpn_present": len(bpn_indices),
        "sugar_present": len(sugar_indices),
        "left_counts": left_counts,
        "right_counts": right_counts,
        "left_voltage_means": left_voltage_means,
        "right_voltage_means": right_voltage_means,
        "left_total": total_left,
        "right_total": total_right,
        "left_max_mv": float(left_voltage_mv.max()),
        "right_max_mv": float(right_voltage_mv.max()),
        "bin_edges": bin_edges,
    }

# ------------------------------------------------------------
# Embody DNg100 activity.
# ------------------------------------------------------------

def embody_dng100(result):
    """Apply the same DNg100-to-body mapping to one neural condition."""

    body = FlyBody(
        x=5.0,
        y=4.0,
        orientation=0.0,
    )

    environment = SpatialEnvironment(
        width=20.0,
        height=10.0,
    )

    readout = LocomotionReadout()
    actuator = LocomotionActuator()

    initial_x = body.x
    initial_y = body.y

    bin_duration_seconds = float(BIN_SIZE / (1000 * ms))

    forward_drives = []
    forward_displacements = []

    for left_spikes, right_spikes in zip(
        result["left_counts"],
        result["right_counts"],
    ):
        forward_drive = readout.update(
            left_spikes=left_spikes,
            right_spikes=right_spikes,
            duration_seconds=bin_duration_seconds,
        )

        displacement = (
            FORWARD_GAIN
            * forward_drive
            * bin_duration_seconds
        )

        command = LocomotionCommand(
            command_type=LocomotionCommandType.FORWARD,
            magnitude=displacement,
        )

        actuator.execute(
            command=command,
            body=body,
            environment=environment,
        )

        forward_drives.append(forward_drive)
        forward_displacements.append(displacement)

    return {
        "body": body,
        "initial_x": initial_x,
        "initial_y": initial_y,
        "forward_drives": np.asarray(forward_drives),
        "forward_displacements": np.asarray(forward_displacements),
        "total_displacement": float(sum(forward_displacements)),
    }

# ------------------------------------------------------------
# Run repeated paired embodied conditions.
# ------------------------------------------------------------

N_TRIALS = 10

bpn_trials = []
bpn_sugar_trials = []

for trial_seed in range(SEED, SEED + N_TRIALS):
    trial_number = trial_seed - SEED + 1

    print(
        f"Running trial {trial_number}/{N_TRIALS} "
        f"(seed={trial_seed})..."
    )

    bpn_result = run_condition(
        include_sugar=False,
        trial_seed=trial_seed,
    )

    bpn_sugar_result = run_condition(
        include_sugar=True,
        trial_seed=trial_seed,
    )

    bpn_body = embody_dng100(bpn_result)
    bpn_sugar_body = embody_dng100(bpn_sugar_result)

    bpn_trials.append({
        "neural": bpn_result,
        "body": bpn_body,
    })

    bpn_sugar_trials.append({
        "neural": bpn_sugar_result,
        "body": bpn_sugar_body,
    })


# ------------------------------------------------------------
# Summarize embodied displacement.
# ------------------------------------------------------------

bpn_displacements = np.asarray([
    trial["body"]["total_displacement"]
    for trial in bpn_trials
])

bpn_sugar_displacements = np.asarray([
    trial["body"]["total_displacement"]
    for trial in bpn_sugar_trials
])

displacement_reductions = 100.0 * (
    1.0
    - bpn_sugar_displacements / bpn_displacements
)


# ------------------------------------------------------------
# Report.
# ------------------------------------------------------------

print()
print("=== EXPERIMENT 16: EMBODIED WALKING/FEEDING COMPETITION ===")
print(f"Trials:                   {N_TRIALS}")
print(f"BPN stimulation:          {float(BPN_RATE / Hz):.0f} Hz")
print(f"Sugar stimulation:        {float(SUGAR_RATE / Hz):.0f} Hz")
print(f"Forward gain:             {FORWARD_GAIN}")

print()
print("Per-trial forward displacement:")
print(
    f"{'Trial':>5s} | "
    f"{'BPN only':>10s} | "
    f"{'BPN+sugar':>10s} | "
    f"{'Reduction':>10s}"
)
print("-" * 47)

for i in range(N_TRIALS):
    print(
        f"{i + 1:5d} | "
        f"{bpn_displacements[i]:10.3f} | "
        f"{bpn_sugar_displacements[i]:10.3f} | "
        f"{displacement_reductions[i]:9.2f}%"
    )

print()
print("Across-trial summary:")

print(
    f"  BPN-only displacement: "
    f"{bpn_displacements.mean():.3f} +/- "
    f"{bpn_displacements.std(ddof=1):.3f}"
)

print(
    f"  BPN+sugar displacement: "
    f"{bpn_sugar_displacements.mean():.3f} +/- "
    f"{bpn_sugar_displacements.std(ddof=1):.3f}"
)

print(
    f"  Displacement reduction: "
    f"{displacement_reductions.mean():.2f}% +/- "
    f"{displacement_reductions.std(ddof=1):.2f}%"
)

print()
print(
    f"Trials with reduced forward displacement: "
    f"{int(np.sum(bpn_sugar_displacements < bpn_displacements))}"
    f"/{N_TRIALS}"
)

assert np.all(bpn_displacements > 0)
assert np.all(
    bpn_sugar_displacements
    < bpn_displacements
)

print()
print(
    "PASS: sugar-pathway recruitment consistently reduced "
    "embodied forward displacement through its effect on "
    "connectome-generated DNg100 activity."
)